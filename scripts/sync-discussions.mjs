import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {githubApi,allPages} from './lib/github.mjs';

export async function syncDiscussions({root,repository,token,api=githubApi(repository,token)}) {
const context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'dist/data.js'),'utf8'),context,{timeout:1000,contextCodeGeneration:{strings:false,wasm:false}});
const collections={event:'events',benefit:'benefits',notice:'notices',food:'foods'};
const labels={event:'活动',benefit:'学生权益',notice:'生活提醒',food:'美食推荐'};
const entries=Object.entries(collections).flatMap(([type,collection])=>context.window.CAMPUS_DATA[collection].map(item=>({type,...item})));
const existingLabels=await allPages(api,'/labels');
if(!existingLabels.some(label=>label.name==='content-discussion'))await api('/labels',{method:'POST',body:{name:'content-discussion',color:'83b8aa',description:'网站内容对应的评论区'}});
const issues=(await allPages(api,'/issues?state=all&labels=content-discussion')).filter(issue=>!issue.pull_request);
const items={};
for(const item of entries) {
  const key=item.type+':'+item.id;
  const marker='<!-- usyd-discussion:'+key+' -->';
  let issue=issues.find(issue=>issue.body?.includes(marker));
  if(!issue) {
    const title=item.title || item.name;
    issue=await api('/issues',{method:'POST',body:{
      title:'[评论] '+title,
      body:marker+'\n\n## '+title+'\n\n'+labels[item.type]+' · `'+key+'`\n\n欢迎在这里分享体验、提问或补充信息。评论会同步显示在网站对应详情页，可以直接上传图片。\n\n[信息来源]('+item.source+')\n\n需要修改收录内容时，请使用仓库的「纠错或更新内容」Issue 模板。',
      labels:['content-discussion']
    }});
    console.log('Created '+key+' → #'+issue.number);
  }
  items[key]=issue.number;
}
const output='// Generated by scripts/sync-discussions.mjs. Keep stable content IDs.\nwindow.CAMPUS_DISCUSSIONS = '+JSON.stringify({repository,items},null,2)+';\n';
const file=path.join(root,'dist/discussions.js');
if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==output)fs.writeFileSync(file,output);
console.log('Linked '+Object.keys(items).length+' content discussions.');

return items;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href) {
  await syncDiscussions({root:path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),repository:process.env.GITHUB_REPOSITORY,token:process.env.GITHUB_TOKEN || process.env.GH_TOKEN});
}
