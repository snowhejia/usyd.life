import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const repository=process.env.GITHUB_REPOSITORY;
const token=process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
if(!/^[A-Za-z0-9-]+\/[A-Za-z0-9_.-]+$/.test(repository || '') || !token)throw new Error('GITHUB_REPOSITORY and GITHUB_TOKEN are required');
const context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'dist/data.js'),'utf8'),context,{timeout:1000,contextCodeGeneration:{strings:false,wasm:false}});
const collections={event:'events',benefit:'benefits',notice:'notices',food:'foods'};
const labels={event:'活动',benefit:'学生权益',notice:'生活提醒',food:'美食推荐'};
const entries=Object.entries(collections).flatMap(([type,collection])=>context.window.CAMPUS_DATA[collection].map(item=>({type,...item})));
async function api(route,body) {
  const response=await fetch('https://api.github.com/repos/'+repository+route,{
    method:body?'POST':'GET',headers:{Accept:'application/vnd.github+json',Authorization:'Bearer '+token,'X-GitHub-Api-Version':'2022-11-28','Content-Type':'application/json'},
    body:body?JSON.stringify(body):undefined,signal:AbortSignal.timeout(20000),redirect:'error'
  });
  if(!response.ok)throw new Error('GitHub request failed: '+response.status+' '+route);
  return response.json();
}
const existingLabels=await api('/labels?per_page=100');
if(!existingLabels.some(label=>label.name==='content-discussion'))await api('/labels',{name:'content-discussion',color:'83b8aa',description:'网站内容对应的评论区'});
const issues=[];
for(let page=1;;page++) {
  const batch=await api('/issues?state=all&labels=content-discussion&per_page=100&page='+page);
  issues.push(...batch.filter(issue=>!issue.pull_request));
  if(batch.length<100)break;
}
const items={};
for(const item of entries) {
  const key=item.type+':'+item.id;
  const marker='<!-- usyd-discussion:'+key+' -->';
  let issue=issues.find(issue=>issue.body?.includes(marker));
  if(!issue) {
    const title=item.title || item.name;
    issue=await api('/issues',{
      title:'[评论] '+title,
      body:marker+'\n\n## '+title+'\n\n'+labels[item.type]+' · `'+key+'`\n\n欢迎在这里分享体验、提问或补充信息。评论会同步显示在网站对应详情页，可以直接上传图片。\n\n[信息来源]('+item.source+')\n\n需要修改收录内容时，请使用仓库的「纠错或更新内容」Issue 模板。',
      labels:['content-discussion']
    });
    console.log('Created '+key+' → #'+issue.number);
  }
  items[key]=issue.number;
}
const output='// Generated by scripts/sync-discussions.mjs. Keep stable content IDs.\nwindow.CAMPUS_DISCUSSIONS = '+JSON.stringify({repository,items},null,2)+';\n';
const file=path.join(root,'dist/discussions.js');
if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==output)fs.writeFileSync(file,output);
console.log('Linked '+Object.keys(items).length+' content discussions.');
